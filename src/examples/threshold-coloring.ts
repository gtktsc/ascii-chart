/**
 * Examples covering threshold coloring behavior.
 */
export const thresholdColoringExamples: readonly SnapshotExample[] = scenarios.flatMap((scenario) =>
  forEachRenderer((renderer: Renderer) => ({
    group: 'plot',
    title: `${scenario.title} [${renderer}]`,
    renderer,
    render: () =>
      withExampleTerminal(() =>
        plot(scenario.data, {
          renderer,
          width: 36,
          height: 10,
          title: scenario.title,
          xLabel: 'sample',
          yLabel: scenario.yLabel,
          interpolation: 'linear',
          color: scenario.baseColor,
          coloring: {
            type: 'conditional',
            getColor: ({ y }) => (y >= scenario.threshold ? scenario.alertColor : undefined),
          },
          yAxis: { domain: [...scenario.yDomain], ticks: [...scenario.yTicks] },
          thresholds: [{ y: scenario.threshold, color: scenario.thresholdColor }],
          legend: {
            position: 'bottom',
            series: scenario.seriesLabel,
            thresholds: scenario.thresholdLabel,
          },
        }),
      ),
  })),
);
